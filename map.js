export const camera = { x: 0, y: 0 };

export function updateCamera(player, ZOOM) {
    const visW = window.innerWidth / ZOOM;
    const visH = window.innerHeight / ZOOM;

    camera.x = player.x + player.width / 2 - visW / 2;
    camera.y = player.y + player.height / 2 - visH / 2;

    const maxX = gridCols * TILE_SIZE - visW;
    const maxY = mapRows.length * TILE_SIZE - visH;

    camera.x = Math.round(Math.max(0, Math.min(camera.x, maxX)));
    camera.y = Math.round(Math.max(0, Math.min(camera.y, maxY)));
}

// ── KOLÍZIA ───────────────────────────
export function getTile(x, y) {
    if (x < 0 || x >= gridCols || y < 0 || y >= mapRows.length) return 0;
    return map[y * gridCols + x];
}

export function isSolidTile(tile) {
    return tile === 0 || [5, 6, 8, 14, 15, 16, 17, 18, 19, 20].includes(tile);
}

export function isWalkable(x, y, width, height) {
    const hb = { x: x + 4, y: y + 4, width: width - 8, height: height - 8 };
    const left = Math.floor(hb.x / TILE_SIZE);
    const right = Math.floor((hb.x + hb.width - 1) / TILE_SIZE);
    const top = Math.floor(hb.y / TILE_SIZE);
    const bottom = Math.floor((hb.y + hb.height - 1) / TILE_SIZE);

    if (left < 0 || right >= gridCols || top < 0 || bottom >= mapRows.length) return false;

    return ![getTile(left, top), getTile(right, top), getTile(left, bottom), getTile(right, bottom)]
        .some(isSolidTile);
}

